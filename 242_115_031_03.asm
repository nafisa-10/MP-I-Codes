.MODEL SMALL
.STACK 100H

.DATA

MENU DB 13,10,'SHOP MENU',13,10
     DB '1. APPLE',13,10
     DB '2. ORANGE',13,10
     DB '3. MANGO',13,10
     DB '4. CHECKOUT',13,10
     DB '5. EXIT',13,10
     DB 'ENTER CHOICE: $'

APPLE_MSG  DB 13,10,'APPLE ADDED$'
ORANGE_MSG DB 13,10,'ORANGE ADDED$'
MANGO_MSG  DB 13,10,'MANGO ADDED$'


APPLE_Q  DB 13,10,'APPLE QUANTITY: $'
ORANGE_Q DB 13,10,'ORANGE QUANTITY: $'
MANGO_Q  DB 13,10,'MANGO QUANTITY: $'
TOTAL_MSG DB 13,10,'TOTAL BILL: $'

APPLE DB 0
ORANGE DB 0
MANGO DB 0

TOTAL DW 0

.CODE

MAIN PROC

MOV AX,@DATA
MOV DS,AX


START:

LEA DX,MENU
MOV AH,09H
INT 21H


; TAKE CHOICE

MOV AH,01H
INT 21H


CMP AL,'1'
JE ADD_APPLE

CMP AL,'2'
JE ADD_ORANGE

CMP AL,'3'
JE ADD_MANGO

CMP AL,'4'
JE CHECKOUT

CMP AL,'5'
JE EXIT


JMP START



; ADD APPLE

ADD_APPLE:

INC APPLE

MOV AX,TOTAL
ADD AX,40
MOV TOTAL,AX

LEA DX,APPLE_MSG
MOV AH,09H
INT 21H

JMP START



; ADD ORANGE

ADD_ORANGE:

INC ORANGE

MOV AX,TOTAL
ADD AX,30
MOV TOTAL,AX

LEA DX,ORANGE_MSG
MOV AH,09H
INT 21H

JMP START



; ADD MANGO

ADD_MANGO:

INC MANGO

MOV AX,TOTAL
ADD AX,60
MOV TOTAL,AX

LEA DX,MANGO_MSG
MOV AH,09H
INT 21H

JMP START



; CHECKOUT

CHECKOUT:


; DISPLAY APPLE QUANTITY

LEA DX,APPLE_Q
MOV AH,09H
INT 21H

MOV DL,APPLE
ADD DL,'0'
MOV AH,02H
INT 21H



; DISPLAY ORANGE QUANTITY

LEA DX,ORANGE_Q
MOV AH,09H
INT 21H

MOV DL,ORANGE
ADD DL,'0'
MOV AH,02H
INT 21H



; Display Mango Quantity

LEA DX,MANGO_Q
MOV AH,09H
INT 21H

MOV DL,MANGO
ADD DL,'0'
MOV AH,02H
INT 21H



; DISPLAY TOTAL BILL

LEA DX,TOTAL_MSG
MOV AH,09H
INT 21H


MOV AX,TOTAL
CALL DISPLAY_NUM


JMP START



; EXIT

EXIT:

MOV AH,4CH
INT 21H


MAIN ENDP



; PROCEDURE TO DISPLAY NUMBER

DISPLAY_NUM PROC

MOV BX,10
MOV CX,0


NEXT:         

MOV DX,0
DIV BX

PUSH DX
INC CX

CMP AX,0
JNE NEXT


PRINT:

POP DX
ADD DL,'0'

MOV AH,02H
INT 21H

LOOP PRINT


RET

DISPLAY_NUM ENDP


END MAIN